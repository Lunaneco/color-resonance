灰色だった窓枠は、家ごとに違う色に塗られていた。青、橙、薄い緑。揃っていない。揃えようとした跡も、なかった。
花屋の軒先では、黄色い花のあいだに、赤い花が一本、まだ名前のないまま咲いていた。
